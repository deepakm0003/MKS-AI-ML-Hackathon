"""Call every API endpoint against the real outputs and write the discovered response shapes.

    python scripts/document_api.py   -> docs/api_contracts.md
The frontend types (dashboard/src/api/types.ts) are written against this document.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))

from fastapi.testclient import TestClient  # noqa: E402

from api.app import app  # noqa: E402

CALLS = [
    ("GET", "/health", None, None),
    ("GET", "/kpis", None, None),
    ("GET", "/meta/filters", None, None),
    ("GET", "/datasets", None, None),
    ("GET", "/datasets/timeline", {"limit": 2}, None),
    ("GET", "/datasets/forecast_detail", {"limit": 1, "Region": "Europe"}, None),
    ("GET", "/series/BSS-001/Europe", None, None),
    ("GET", "/hierarchy", {"level": "family"}, None),
    ("GET", "/intelligence/briefing", None, None),
    ("GET", "/intelligence/report", None, None),
    ("GET", "/intelligence/recommendations", {"priority": "CRITICAL", "limit": 1}, None),
    ("GET", "/views/timeline", {"family": "Thermal Management", "region": "Europe"}, None),
    ("GET", "/views/breakdown", {"dim": "region", "top": 3}, None),
    ("GET", "/scenario/config", None, None),
    ("POST", "/scenario", None, {"shocks": {"pmi": -3}, "region_overlay": {"Europe": -5}}),
]


def shape(v, depth=0, max_depth=4):
    """Compact type description of a JSON value."""
    if depth > max_depth:
        return "..."
    if isinstance(v, dict):
        if len(v) > 40:
            k0 = next(iter(v))
            return {f"<{len(v)} keys, e.g. {k0!r}>": shape(v[k0], depth + 1)}
        return {k: shape(x, depth + 1) for k, x in v.items()}
    if isinstance(v, list):
        return [shape(v[0], depth + 1)] if v else []
    if isinstance(v, bool):
        return "boolean"
    if isinstance(v, (int, float)):
        return "number"
    if v is None:
        return "null"
    return "string"


def main():
    c = TestClient(app)
    out = ["# API contracts (discovered from live responses)", "",
           "Generated by `python scripts/document_api.py` against the real pipeline outputs. "
           "Shapes show field types; `[x]` is a list of x. The dashboard's TypeScript types "
           "(`dashboard/src/api/types.ts`) mirror these.", ""]
    for method, path, params, body in CALLS:
        r = c.request(method, path, params=params, json=body)
        out += [f"## `{method} {path}`" + (f" — params `{params}`" if params else "") +
                (f" — body `{json.dumps(body)}`" if body else ""), "", f"Status: **{r.status_code}**", ""]
        if r.status_code == 200:
            out += ["```json", json.dumps(shape(r.json()), indent=2)[:6000], "```", ""]
        else:
            out += [f"`{r.text[:300]}`", ""]
    (ROOT / "docs" / "api_contracts.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(l for l in out if l.startswith("## ") or l.startswith("Status")))


if __name__ == "__main__":
    main()
